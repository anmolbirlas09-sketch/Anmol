       (select sum(p.meters) from public.grey_fabric_production p where p.beam_id = b.id), b.updated_by
from public.beams b where b.status = 'finished' and b.loom_id is not null;
update public.beams set actual_finish_date = (finished_at at time zone 'Asia/Kolkata')::date
 where status = 'finished' and finished_at is not null and actual_finish_date is null;

-- ---------------------------------------------------------------------------
-- Shop-floor RPCs: unload, load (optionally replacing the running beam)
-- ---------------------------------------------------------------------------
create or replace function public.unload_beam(p_beam_id uuid)
returns public.beams
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_beam public.beams;
begin
  select * into v_beam from public.beams where id = p_beam_id for update;
  if not found then
    raise exception 'Beam not found' using errcode = 'WV004';
  end if;
  perform public.require_factory_access(v_beam.factory_id);
  -- Same rule as before: taking a beam off unfinished is an owner / supervisor decision.
  if not public.can_edit_factory(v_beam.factory_id) then
    raise exception 'Only an owner or supervisor can unload a beam' using errcode = 'WV005';
  end if;
  if v_beam.status <> 'on_loom' then
    raise exception 'Beam % is not on a loom', public.beam_label(v_beam.beam_no, v_beam.card_no) using errcode = 'WV004';
  end if;
  update public.beams set status = 'prepared' where id = p_beam_id returning * into v_beam;
  return v_beam;
end;
$$;

create or replace function public.finish_beam(p_beam_id uuid)
returns public.beams
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_beam public.beams;
begin
  select * into v_beam from public.beams where id = p_beam_id for update;
  if not found then
    raise exception 'Beam not found' using errcode = 'WV004';
  end if;
  perform public.require_factory_access(v_beam.factory_id);
