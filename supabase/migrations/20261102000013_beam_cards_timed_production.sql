-- When the reading was taken. A night-shift time before 08:00 belongs to the
-- morning after the shift date (night 8 pm – 8 am is dated by its evening).
-- Without a time: the moment it was entered, if that was on the production date
-- (or the night after it); otherwise the end of the production date.
create or replace function public.production_moment(p_date date, p_time time, p_shift text, p_created timestamptz)
returns timestamp
language sql
stable
set search_path = ''
as $$
  select case
    when p_time is not null and p_shift = 'night' and p_time < time '08:00' then (p_date + 1) + p_time
    when p_time is not null then p_date + p_time
    when (p_created at time zone 'Asia/Kolkata')::date in (p_date, p_date + 1) then (p_created at time zone 'Asia/Kolkata')
    else p_date + time '23:59:59'
  end
$$;

-- The loom's last counter reading before a moment (same loom, any beam).
create or replace function public.previous_counter_reading(p_loom_id uuid, p_at timestamp, p_exclude uuid default null,
                                                           out reading numeric, out reading_at timestamp, out reset boolean)
language sql
stable
security definer
set search_path = ''
as $$
  select p.counter_reading, p.reading_at, p.counter_reset
  from public.grey_fabric_production p
  where p.loom_id = p_loom_id and p.counter_reading is not null and p.reading_at <= p_at
    and (p_exclude is null or p.id <> p_exclude)
  order by p.reading_at desc, p.created_at desc
  limit 1
$$;
grant execute on function public.previous_counter_reading(uuid, timestamp, uuid) to authenticated;

-- Existing entries: when they were made (their production date + the moment entered).
update public.grey_fabric_production
   set reading_at = public.production_moment(entry_date, production_time, shift, created_at)
 where reading_at is null;

create or replace function public.trg_grey_production_reading()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_prev record;
  v_diff numeric;
begin
  -- Shift from the actual time when not chosen: day 08:00–20:00, night otherwise.
  if new.shift is null and new.production_time is not null then
    new.shift := case when new.production_time >= time '08:00' and new.production_time < time '20:00' then 'day' else 'night' end;
  end if;
  new.reading_at := public.production_moment(new.entry_date, new.production_time, new.shift, coalesce(new.created_at, now()));

  if tg_op = 'UPDATE' then
    return new;   -- earlier readings and the metres worked out from them are never recalculated
  end if;

  new.meters_source := case when new.meters is not null then 'manual' end;
  if new.counter_reading is not null and not new.counter_reset then
    select * into v_prev from public.previous_counter_reading(new.loom_id, new.reading_at);
    if v_prev.reading is not null then
      new.previous_reading := v_prev.reading;
      v_diff := new.counter_reading - v_prev.reading;
      if v_diff < 0 and new.meters is null then
        raise exception 'Counter reading % is lower than the previous reading % (%). If the counter was reset or the meter replaced, tick "Counter reset" and enter the metres if known.',
            trim_scale(new.counter_reading), trim_scale(v_prev.reading), to_char(v_prev.reading_at, 'DD-MM-YYYY HH24:MI')
          using errcode = 'WV004';
      end if;
      if new.meters is null and v_diff > 0 then
        new.meters := v_diff;
        new.meters_source := 'counter';
      elsif new.meters is null and v_diff = 0 then
        new.meters_source := 'counter';   -- no fabric since the last reading (metres stay blank, not 0)
      end if;
    end if;
  end if;

  if new.meters is null and coalesce(new.wasted_meters, 0) > 0 then
    raise exception 'Wasted metres need the production metres' using errcode = 'WV004';
  end if;
  if new.meters is not null and new.wasted_meters > new.meters then
    raise exception 'Wasted metres (%) cannot be more than production metres (%)', trim_scale(new.wasted_meters), trim_scale(new.meters) using errcode = 'WV004';
  end if;
  return new;
end;
$$;
