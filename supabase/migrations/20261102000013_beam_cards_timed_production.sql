-- =============================================================================
-- 0013 · Digital beam card + loading history + time-stamped production
--
-- Beam card (every user-entered field optional — NULL when not filled in):
--   beam_no, created_date (beam making date), fabric_quality_id,
--   fabric_specification_id, factory_id are no longer required.
--   New card fields on beams: reed, warp/weft yarn (used when no
--   specification is chosen), total_ends, reed_space_in, picks_on_loom,
--   counter meter (= warp_length_m, kept), rolling_meter, warp/gross/finished/
--   weft weights, weave, getting_date, expected_finish_date, actual_finish_date.
--   card_no: system number so a beam without a beam number is still identifiable
--   ("CARD-12"). Views show beam_no = the entered number or CARD-n.
--   Quality / specification can be filled in later; production already recorded
--   on that beam then moves to it (only when it had none — never re-labelled).
--
-- Beam ↔ loom history: beam_loom_events (loaded / unloaded / finished), written by
-- trigger; existing loads and finishes back-filled. A beam can now be unloaded
-- after production (it keeps its history and can be loaded again), and
-- load_beam() can replace the beam running on the loom (finish or unload it).
--
-- Production entries gain production_time (actual time of the reading),
-- counter_reading, previous_reading, meters_source ('manual' / 'counter'),
-- counter_reset and reading_at (date + time, used to keep loom history in order).
--   Production metres = current reading − previous reading on the same loom,
--   only when the previous reading exists, the counter was not reset and the
--   metres were not typed in. Earlier entries are never recalculated.
--   Metres, wasted metres and roll length are optional (an entry needs metres
--   or a counter reading).
-- =============================================================================

