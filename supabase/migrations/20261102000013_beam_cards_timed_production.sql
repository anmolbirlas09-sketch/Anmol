  p_loom_id           uuid,
  p_fabric_quality_id uuid default null,
  p_meters            numeric default null,
  p_wasted_meters     numeric default null,
  p_roll_length_m     numeric default null,
  p_entry_date        date default null,
  p_shift             text default null,
  p_gsm               numeric default null,
  p_width_m           numeric default null,
  p_weighed_kg        numeric default null,
  p_warp_kg           numeric default null,
