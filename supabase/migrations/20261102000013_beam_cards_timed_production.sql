-- ---------------------------------------------------------------------------
-- Specification on a beam: optional; may be filled in later
-- ---------------------------------------------------------------------------
create or replace function public.trg_beam_spec()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_quality uuid;
  v_only uuid;
  v_active boolean;
  v_label text := public.beam_label(new.beam_no, new.card_no);
  v_has_prod boolean;
begin
  if tg_op = 'UPDATE' and new.fabric_specification_id is not distinct from old.fabric_specification_id
     and new.fabric_quality_id is not distinct from old.fabric_quality_id then
    return new;
  end if;
  if tg_op = 'UPDATE' then
    v_has_prod := exists (select 1 from public.grey_fabric_production p where p.beam_id = old.id);
    -- Filling in a blank is fine; changing what production was recorded against is not.
    if v_has_prod and old.fabric_specification_id is not null and new.fabric_specification_id is distinct from old.fabric_specification_id then
      raise exception 'Beam % already has production; its specification cannot change', v_label using errcode = 'WV004';
    end if;
    if v_has_prod and old.fabric_quality_id is not null and new.fabric_quality_id is distinct from old.fabric_quality_id then
      raise exception 'Beam % already has production; its fabric quality cannot change', v_label using errcode = 'WV004';
    end if;
  end if;

  if new.fabric_specification_id is not null then
    select s.fabric_quality_id, s.active into v_quality, v_active from public.fabric_specifications s where s.id = new.fabric_specification_id;
    if not found then
      raise exception 'Specification not found' using errcode = 'WV004';
    end if;
    if new.fabric_quality_id is not null and new.fabric_quality_id <> v_quality then
      raise exception 'Specification % does not belong to %',
          (select spec_code from public.fabric_specifications where id = new.fabric_specification_id),
          (select name from public.fabric_qualities where id = new.fabric_quality_id)
        using errcode = 'WV004';
    end if;
    new.fabric_quality_id := v_quality;
    if not v_active and (tg_op = 'INSERT' or new.fabric_specification_id is distinct from old.fabric_specification_id) then
      raise exception 'That specification is deactivated' using errcode = 'WV004';
    end if;
  elsif new.fabric_quality_id is not null then
    -- A parent with exactly one active specification: use it, unless the card says otherwise.
    v_only := public.only_spec_of(new.fabric_quality_id);
    if v_only is not null and exists (
      select 1 from public.fabric_specifications s
      where s.id = v_only
        and (new.reed is null or s.reed is null or s.reed = new.reed)
        and (new.warp_yarn_quality_id is null or s.warp_yarn_quality_id is null or s.warp_yarn_quality_id = new.warp_yarn_quality_id)
        and (new.weft_yarn_quality_id is null or s.weft_yarn_quality_id is null or s.weft_yarn_quality_id = new.weft_yarn_quality_id)
    ) then
      new.fabric_specification_id := v_only;
    end if;
  end if;
  return new;
end;
$$;

-- Production recorded before the quality / specification was known follows the beam.
create or replace function public.trg_beam_fill_production()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.fabric_quality_id is distinct from old.fabric_quality_id
     or new.fabric_specification_id is distinct from old.fabric_specification_id then
    update public.grey_fabric_production p
       set fabric_quality_id = coalesce(p.fabric_quality_id, new.fabric_quality_id),
           fabric_specification_id = coalesce(p.fabric_specification_id, new.fabric_specification_id)
     where p.beam_id = new.id
       and (p.fabric_quality_id is null or p.fabric_specification_id is null);
  end if;
  return null;
end;
$$;
create trigger beams_fill_production
  after update of fabric_quality_id, fabric_specification_id on public.beams
  for each row execute function public.trg_beam_fill_production();

-- ---------------------------------------------------------------------------
-- Beam state: unloading after production is allowed (history stays)
-- ---------------------------------------------------------------------------
create or replace function public.trg_beam_before()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_loom   public.looms;
  v_other  text;
  v_assigned text;
  v_beam_spec text;
  v_label text := public.beam_label(new.beam_no, new.card_no);
begin
  if new.status = 'on_loom' and (tg_op = 'INSERT' or old.status <> 'on_loom' or old.loom_id is distinct from new.loom_id) then
    if new.loom_id is null then
      raise exception 'Pick a loom to load beam % on', v_label using errcode = 'WV004';
    end if;
    select * into v_loom from public.looms where id = new.loom_id for update;
    if not found then
      raise exception 'Loom not found' using errcode = 'WV002';
    end if;
    if not v_loom.active then
      raise exception 'Loom % is deactivated', v_loom.machine_no using errcode = 'WV002';
    end if;
    if v_loom.status = 'maintenance' then
      raise exception 'Loom % is under maintenance', v_loom.machine_no using errcode = 'WV002';
    end if;
    -- Only a beam whose specification is known can conflict with the loom's set-up.
    if v_loom.fabric_specification_id is not null and new.fabric_specification_id is not null
       and v_loom.fabric_specification_id <> new.fabric_specification_id then
      select spec_code into v_assigned from public.fabric_specifications where id = v_loom.fabric_specification_id;
      select spec_code into v_beam_spec from public.fabric_specifications where id = new.fabric_specification_id;
      raise exception 'Loom % is set up for %; beam % is %. Change the loom''s specification in Settings first.',
          v_loom.machine_no, v_assigned, v_label, v_beam_spec
        using errcode = 'WV002';
    end if;
    select public.beam_label(b.beam_no, b.card_no) into v_other
    from public.beams b
    where b.loom_id = new.loom_id and b.status = 'on_loom' and b.id <> new.id;
    if found then
      raise exception 'Loom % already has beam % running. Finish or unload it first.', v_loom.machine_no, v_other
        using errcode = 'WV002',
              detail = json_build_object('machine_no', v_loom.machine_no, 'running_beam_no', v_other)::text;
    end if;
    new.loaded_at   := coalesce(new.loaded_at, now());
    new.finished_at := null;
    new.factory_id  := v_loom.factory_id;   -- the beam is now physically at this factory
  end if;

  if new.status = 'finished' and (tg_op = 'INSERT' or old.status <> 'finished') then
    new.finished_at := coalesce(new.finished_at, now());
    new.actual_finish_date := coalesce(new.actual_finish_date, (new.finished_at at time zone 'Asia/Kolkata')::date);
  end if;

  if new.status = 'prepared' and tg_op = 'UPDATE' and old.status <> 'prepared' then
    -- A finished beam is closed; one taken off a loom (unloaded) keeps its production history.
    if old.status = 'finished' and exists (select 1 from public.grey_fabric_production p where p.beam_id = new.id) then
      raise exception 'Beam % is finished and has production; it cannot be reopened', v_label using errcode = 'WV004';
    end if;
    new.loom_id := null;
    new.loaded_at := null;
    new.finished_at := null;
  end if;

  return new;
end;
$$;

