  return v_beam;
end;
$$;

drop function public.load_beam(uuid, uuid);
create function public.load_beam(p_beam_id uuid, p_loom_id uuid, p_replace text default null)
returns public.beams
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_beam public.beams;
  v_loom public.looms;
  v_running uuid;
begin
  if p_replace is not null and p_replace not in ('finish', 'unload') then
    raise exception 'Unknown replace option' using errcode = 'WV004';
  end if;
  select * into v_beam from public.beams where id = p_beam_id for update;
  if not found then
    raise exception 'Beam not found' using errcode = 'WV004';
  end if;
  select * into v_loom from public.looms where id = p_loom_id;
  if not found then
    raise exception 'Loom not found' using errcode = 'WV002';
  end if;
  -- A beam not yet at any shed may be loaded by anyone who works at the loom's shed.
  if v_beam.factory_id is not null then
    perform public.require_factory_access(v_beam.factory_id);
  end if;
  perform public.require_factory_access(v_loom.factory_id);
  if v_beam.status <> 'prepared' then
    raise exception 'Beam % is % and cannot be loaded', public.beam_label(v_beam.beam_no, v_beam.card_no), replace(v_beam.status::text, '_', ' ')
      using errcode = 'WV004';
  end if;
  if p_replace is not null then
    select id into v_running from public.beams where loom_id = p_loom_id and status = 'on_loom' for update;
    if found then
      if p_replace = 'finish' then
        perform public.finish_beam(v_running);
      else
        perform public.unload_beam(v_running);
      end if;
    end if;
  end if;
  update public.beams
     set status = 'on_loom', loom_id = p_loom_id, loaded_at = now()
   where id = p_beam_id
  returning * into v_beam;
  return v_beam;
end;
$$;

grant execute on function public.load_beam(uuid, uuid, text), public.unload_beam(uuid), public.finish_beam(uuid),
                          public.beam_label(text, bigint) to authenticated;

