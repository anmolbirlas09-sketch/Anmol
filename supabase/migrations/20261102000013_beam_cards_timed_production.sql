-- Quality / specification come from the beam; both may still be blank.
create or replace function public.trg_grey_production_before()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_beam public.beams;
  v_quality text;
  v_spec text;
  v_label text;
begin
  select * into v_beam from public.beams where id = new.beam_id;
  v_label := public.beam_label(v_beam.beam_no, v_beam.card_no);

  if new.fabric_quality_id is null then
    new.fabric_quality_id := v_beam.fabric_quality_id;
  elsif new.fabric_quality_id is distinct from v_beam.fabric_quality_id then
    if v_beam.fabric_quality_id is null then
      raise exception 'Beam % has no fabric quality yet; set it on the beam card first', v_label using errcode = 'WV004';
    end if;
    select name into v_quality from public.fabric_qualities where id = v_beam.fabric_quality_id;
    raise exception 'Beam % is weaving %, not the fabric quality selected', v_label, v_quality
      using errcode = 'WV004';
  end if;
  if new.fabric_specification_id is null then
    new.fabric_specification_id := v_beam.fabric_specification_id;
  elsif new.fabric_specification_id is distinct from v_beam.fabric_specification_id then
    if v_beam.fabric_specification_id is null then
      raise exception 'Beam % has no specification yet; set it on the beam card first', v_label using errcode = 'WV004';
    end if;
    select spec_code into v_spec from public.fabric_specifications where id = v_beam.fabric_specification_id;
    raise exception 'Beam % is weaving specification %, not the specification selected', v_label, v_spec
      using errcode = 'WV004';
  end if;

  if tg_op = 'UPDATE' and new.beam_id = old.beam_id and new.loom_id = old.loom_id then
    return new;   -- corrections on an existing entry
  end if;
  if new.loom_id is null then
    new.loom_id := v_beam.loom_id;
  end if;
  if v_beam.status <> 'on_loom' then
    raise exception 'Beam % is not running on a loom (status: %)', v_label, v_beam.status using errcode = 'WV004';
  end if;
  if new.loom_id <> v_beam.loom_id then
    raise exception 'Beam % is running on a different loom', v_label using errcode = 'WV004';
  end if;
  return new;
end;
$$;

