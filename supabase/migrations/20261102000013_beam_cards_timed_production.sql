create table public.beam_loom_events (
  id          uuid primary key default gen_random_uuid(),
  beam_id     uuid not null references public.beams (id) on delete cascade,
  loom_id     uuid not null references public.looms (id),
  event       text not null check (event in ('loaded', 'unloaded', 'finished')),
  at          timestamptz not null default now(),
  meters_so_far numeric(14,2),
  created_by  uuid default auth.uid(),
  seq         bigint generated always as identity   -- keeps unload-then-load in the same instant in order
);
create index beam_loom_events_beam_idx on public.beam_loom_events (beam_id, at, seq);
create index beam_loom_events_loom_idx on public.beam_loom_events (loom_id, at);
comment on table public.beam_loom_events is 'Every load, unload and finish of a beam on a loom (written by trigger)';

alter table public.beam_loom_events enable row level security;
grant select on public.beam_loom_events to authenticated;
create policy beam_loom_events_select on public.beam_loom_events for select to authenticated
  using (public.can_access_factory(public.loom_factory_id(loom_id)));

create or replace function public.trg_beam_events()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_m numeric;
begin
  select sum(p.meters) into v_m from public.grey_fabric_production p where p.beam_id = new.id;
  if tg_op = 'INSERT' then
    if new.status = 'on_loom' then
      insert into public.beam_loom_events (beam_id, loom_id, event, at) values (new.id, new.loom_id, 'loaded', new.loaded_at);
    end if;
    return null;
  end if;
  if old.status = 'on_loom' and (new.status <> 'on_loom' or new.loom_id is distinct from old.loom_id) then
    insert into public.beam_loom_events (beam_id, loom_id, event, at, meters_so_far)
    values (new.id, old.loom_id, case when new.status = 'finished' then 'finished' else 'unloaded' end,
            case when new.status = 'finished' then coalesce(new.finished_at, now()) else now() end, v_m);
  end if;
  if new.status = 'on_loom' and (old.status <> 'on_loom' or new.loom_id is distinct from old.loom_id) then
    insert into public.beam_loom_events (beam_id, loom_id, event, at, meters_so_far) values (new.id, new.loom_id, 'loaded', new.loaded_at, v_m);
  end if;
  return null;
end;
$$;
create trigger beams_events
  after insert or update of status, loom_id on public.beams
  for each row execute function public.trg_beam_events();

create view public.v_beam_loom_events with (security_invoker = true) as
  select e.id, e.beam_id, public.beam_label(b.beam_no, b.card_no) as beam_no, e.loom_id, l.machine_no, l.factory_id,
         e.event, e.at, e.seq, e.meters_so_far, e.created_by, u.name as created_by_name
  from public.beam_loom_events e
  join public.beams b on b.id = e.beam_id
  join public.looms l on l.id = e.loom_id
  left join public.app_users u on u.id = e.created_by;
grant select on public.v_beam_loom_events to authenticated;

-- Back-fill from what the beams already record.
