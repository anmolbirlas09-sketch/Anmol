  left join public.yarn_qualities sf on sf.id = s.weft_yarn_quality_id
  left join public.yarn_qualities bw on bw.id = b.warp_yarn_quality_id
  left join public.yarn_qualities bf on bf.id = b.weft_yarn_quality_id
